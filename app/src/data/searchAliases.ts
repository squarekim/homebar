/** IBA 레시피 주소에서 영어 이름을 뽑는다 — iba-world.com/iba-cocktail/old-fashioned/ → 'old fashioned' */
export function ibaEnglishName(url: string | undefined): string | undefined {
  const m = url?.match(/iba-cocktail\/([^/?#]+)/);
  return m?.[1] ? decodeURIComponent(m[1]).replace(/-/g, ' ') : undefined;
}

