/** 태그 라벨을 사전 키로 정규화 ("셰리 캐스크"→"셰리", "아일라 · 3"→"아일라", "하이랜드(해안)"→"하이랜드") */
export function normalizeTerm(label: string): string {
  let t = label.replace(/^\+\s*/, '').trim();
  t = t.replace(/\s*·.*$/, '');       // " · 3", " · 결손"
  t = t.replace(/\s*겹침.*$/, '');    // " 겹침 (4)"
  t = t.replace(/\s*\(.*?\)\s*$/, ''); // "(해안)", "(스카이)"
  t = t.replace(/\s*캐스크$/, '');    // "셰리 캐스크"
  return t.trim();
}

export function lookupTerm(termOrLabel: string): string | undefined {
  return GLOSSARY[termOrLabel] ?? GLOSSARY[normalizeTerm(termOrLabel)];
}
