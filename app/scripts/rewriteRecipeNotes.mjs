export function rewriteNotes(dry = false) {
  const text = readFileSync(SEED, 'utf8');
  const start = text.indexOf('{', text.indexOf('export const SEED'));
  const head = text.slice(0, start);
  const tailMatch = text.slice(start).match(/\s+as\s+RawData\s*;?\s*$/);
  const tail = tailMatch ? tailMatch[0] : '';
  const data = JSON.parse(text.slice(start, text.length - tail.length));
  let changed = 0;
  const skipped = [];
  for (const [i, name, note] of NOTES) {
    const r = data.recipes[i];
    if (!r || r.n !== name) { skipped.push(`${i} ${name}`); continue; }
    if ((r.note ?? '') === note) continue;
    if (note) r.note = note; else delete r.note;
    changed++;
  }
  if (!dry) writeFileSync(SEED, head + JSON.stringify(data) + tail);
  return { changed, skipped };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = rewriteNotes(process.argv.includes('--dry'));
  console.log(`메모 ${r.changed}건 변경${r.skipped.length ? ` · 이름이 달라 건너뜀: ${r.skipped.join(', ')}` : ''}`);
}
